"""Command-line entry points: python -m app.cli <command>."""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import json
import logging
import sys
import time
from pathlib import Path

from alembic import command
from alembic.config import Config

from app.config import get_settings

BACKEND_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = BACKEND_DIR.parent
log = logging.getLogger("cac")


def _alembic_cfg() -> Config:
    cfg = Config(str(BACKEND_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "migrations"))
    return cfg


def cmd_migrate(_: argparse.Namespace) -> None:
    command.upgrade(_alembic_cfg(), "head")
    print("migrations applied")


def cmd_generate(a: argparse.Namespace) -> None:
    from app.synthetic.generate import generate

    as_of = dt.date.fromisoformat(a.as_of) if a.as_of else dt.date.today()
    summary, _ = generate(Path(a.out), as_of, stale_entity=a.stale_entity)
    print(json.dumps(summary, indent=2, ensure_ascii=False))


def cmd_validate(a: argparse.Namespace) -> None:
    from app.importer.validate import validate_package

    res = validate_package(Path(a.folder), allow_live=get_settings().allow_live_import)
    print(json.dumps(res.summary(), indent=2, ensure_ascii=False, default=str))
    sys.exit(0 if res.ok else 1)


def cmd_import(a: argparse.Namespace) -> None:
    from app.db import session_factory
    from app.importer.load import import_package
    from app.services.refresh import run_refresh

    with session_factory()() as db:
        res, run = import_package(db, Path(a.folder), force=a.force)
        print(json.dumps({"run_id": run.id if run else None, "skipped_identical": run is None, **res.summary()},
                         indent=2, ensure_ascii=False, default=str))
        if run is not None and run.status == "loaded" and not a.no_refresh:
            print(json.dumps({"refresh": run_refresh(db)}, indent=2))
        if not res.ok:
            sys.exit(1)


def cmd_refresh(_: argparse.Namespace) -> None:
    from app.db import session_factory
    from app.services.refresh import run_refresh

    with session_factory()() as db:
        print(json.dumps(run_refresh(db), indent=2))


def cmd_seed_demo(a: argparse.Namespace) -> None:
    from app.synthetic.demo_seed import seed_demo

    as_of = dt.date.fromisoformat(a.as_of) if a.as_of else None
    result = seed_demo(Path(a.data_dir), as_of=as_of, stale_entity=a.stale_entity)
    print(json.dumps(result, indent=2, ensure_ascii=False, default=str))


def cmd_scheduler(a: argparse.Namespace) -> None:
    """Long-running refresh loop: import new packages from the inbox (if configured), then re-evaluate."""
    from app.db import session_factory
    from app.importer.load import import_package
    from app.services.refresh import run_refresh

    s = get_settings()
    interval = a.every_minutes or s.scheduler_interval_minutes
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    while True:
        try:
            with session_factory()() as db:
                if s.import_inbox:
                    for pkg in sorted(p for p in Path(s.import_inbox).iterdir() if p.is_dir()):
                        res, run = import_package(db, pkg)
                        if run is not None:
                            log.info("import %s -> %s", pkg.name, run.status)
                log.info("refresh %s", run_refresh(db))
        except Exception:  # keep the loop alive; failures are logged and retried next cycle
            log.exception("scheduled refresh failed")
        if a.once:
            return
        time.sleep(interval * 60)


def cmd_create_user(a: argparse.Namespace) -> None:
    from app.db import session_factory
    from app.models.records import AppUser
    from app.services.audit import audit

    with session_factory()() as db:
        u = AppUser(email=a.email, display_name=a.name, role=a.role, salesperson_code=a.salesperson_code,
                    entra_object_id=a.entra_object_id, active=True)
        db.add(u)
        db.flush()
        audit(db, None, "user_created", "app_user", u.id, {"role": a.role, "via": "cli"})
        db.commit()
        print(f"created user {u.id} {u.email} ({u.role})")


def cmd_contract_docs(_: argparse.Namespace) -> None:
    from app.importer.contract import CONTRACT_VERSION, FILES

    out = [f"<!-- generated by `python -m app.cli contract-docs` from app/importer/contract.py (contract v{CONTRACT_VERSION}) -->"]
    for f in FILES:
        out += ["", f"### `{f.name}`", "", f"**Grain:** {f.grain}  ", f"**Purpose:** {f.purpose}"]
        if f.keys:
            out.append(f"  \n**Unique key:** {', '.join(f'`{k}`' for k in f.keys)}")
        out += ["", "| Column | Type | Required | Description | Example |", "|---|---|---|---|---|"]
        for c in f.columns:
            t = c.type + (f" ({' / '.join(c.enum)})" if c.enum else "")
            out.append(f"| `{c.name}` | {t} | {'yes' if c.required else 'no'} | {c.description} | `{c.example}` |")
    print("\n".join(out))


def cmd_contract_templates(a: argparse.Namespace) -> None:
    from app.importer.contract import FILES

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for f in FILES:
        with (out / f.name).open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow([c.name for c in f.columns])
            w.writerow([c.example for c in f.columns])
    print(f"templates written to {out}")


def main() -> None:
    p = argparse.ArgumentParser(prog="python -m app.cli")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("migrate").set_defaults(fn=cmd_migrate)
    g = sub.add_parser("generate-synthetic")
    g.add_argument("--out", default=str(REPO_DIR / "data" / "synthetic"))
    g.add_argument("--as-of")
    g.add_argument("--stale-entity", choices=["JC", "PM"])
    g.set_defaults(fn=cmd_generate)
    v = sub.add_parser("validate")
    v.add_argument("folder")
    v.set_defaults(fn=cmd_validate)
    i = sub.add_parser("import")
    i.add_argument("folder")
    i.add_argument("--force", action="store_true")
    i.add_argument("--no-refresh", action="store_true")
    i.set_defaults(fn=cmd_import)
    sub.add_parser("refresh").set_defaults(fn=cmd_refresh)
    s = sub.add_parser("seed-demo")
    s.add_argument("--data-dir", default=str(REPO_DIR / "data" / "synthetic"))
    s.add_argument("--as-of")
    s.add_argument("--stale-entity", choices=["JC", "PM"])
    s.set_defaults(fn=cmd_seed_demo)
    sc = sub.add_parser("scheduler")
    sc.add_argument("--every-minutes", type=int)
    sc.add_argument("--once", action="store_true")
    sc.set_defaults(fn=cmd_scheduler)
    cu = sub.add_parser("create-user")
    cu.add_argument("--email", required=True)
    cu.add_argument("--name", required=True)
    cu.add_argument("--role", required=True, choices=["sales", "manager", "admin"])
    cu.add_argument("--salesperson-code")
    cu.add_argument("--entra-object-id")
    cu.set_defaults(fn=cmd_create_user)
    sub.add_parser("contract-docs").set_defaults(fn=cmd_contract_docs)
    t = sub.add_parser("contract-templates")
    t.add_argument("--out", default=str(REPO_DIR / "data" / "templates"))
    t.set_defaults(fn=cmd_contract_templates)
    args = p.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
